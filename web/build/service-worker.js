// Vite plugin: writes sw.js, the service worker that lets the app open with no connection.
//
// What it keeps on the device:
//  - the app itself (the page, its scripts, styles and fonts), fetched when the worker installs
//  - the food lists, kept the first time each is downloaded
// What it never touches: anything on another site, so sign-in, the database and the server functions
// always go to the network.
//
// The page is fetched from the network first, so a new version is picked up as soon as there is a
// connection; the kept copy is used only when the network does not answer.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const worker = (version, shell, lists) => `// Generated by build/service-worker.js. Do not edit.
const CACHE = 'ember-${version}';
const SHELL = ${JSON.stringify(shell)};
// The food lists have their own keep, which outlives new versions of the app: a list is only fetched
// again when its contents (and so its name) change.
const LISTS_CACHE = 'ember-lists';
const LISTS = ${JSON.stringify(lists)};
const keepLists = () =>
  caches.open(LISTS_CACHE).then(async c => {
    const want = LISTS.map(l => new URL(l, self.location).href);
    for (const req of await c.keys()) if (!want.includes(req.url)) await c.delete(req);
    for (const url of want) if (!(await c.match(url))) await c.add(url).catch(() => {});
  });
self.addEventListener('install', e => {
  // the page itself must be kept or the install fails and is retried later; one missing extra file must not sink the rest
  e.waitUntil(caches.open(CACHE).then(c => c.add(SHELL[0]).then(() => Promise.all(SHELL.slice(1).map(u => c.add(u).catch(() => {}))))).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('ember-') && k !== CACHE && k !== LISTS_CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()),
  );
  keepLists(); // in the background: about 12 MB the first time, nothing after that until a list changes
});
const isList = url => /\\/foods-[a-z-]+\\.[0-9a-f]{8}\\.json$/.test(url.pathname);
const keepsForever = url => /\\/assets\\//.test(url.pathname) || isList(url);
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  // only the app itself is kept for offline use; the privacy and terms pages are read online
  if (req.mode === 'navigate' && /\\/(index\\.html)?$/.test(url.pathname)) {
    // the page: network first, the kept copy when there is no answer within a few seconds
    e.respondWith(
      Promise.race([fetch(req), new Promise((_, no) => setTimeout(no, 4000))])
        .then(res => { if (res.ok && !res.redirected) caches.open(CACHE).then(c => c.put('./', res.clone())); return res; })
        .catch(() => caches.match('./', { ignoreSearch: true }).then(r => r || fetch(req))),
    );
    return;
  }
  if (keepsForever(url)) {
    // named by their contents, so a kept copy is always right
    e.respondWith(
      caches.match(req).then(hit => hit || fetch(req).then(res => { if (res.ok) caches.open(isList(url) ? LISTS_CACHE : CACHE).then(c => c.put(req, res.clone())); return res; })),
    );
  }
});
`;

export default function serviceWorker() {
  return {
    name: 'ember-service-worker',
    apply: 'build',
    // After everything is written, so the list is the files that really exist. (The list Vite holds while
    // building also names empty script files that it then drops; asking the browser to keep those made the
    // whole worker fail to install.)
    writeBundle(options) {
      const dir = options.dir;
      const walk = d =>
        fs
          .readdirSync(d, { withFileTypes: true })
          .flatMap(e => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
      const all = walk(dir)
        .map(f => path.relative(dir, f).split(path.sep).join('/'))
        .sort();
      const lists = all.filter(f => /^foods-.*\.json$/.test(f)).map(f => './' + f);
      // the app itself: its scripts, styles and fonts, the manifest and the icons a home screen uses.
      // Not the start-up pictures or the link-preview image (large, and not needed to run), nor the policy pages.
      const shell = [
        './', // kept as './' and not './index.html': some hosts redirect one to the other, and a browser will not open a redirected page from the offline store
        ...all
          .filter(
            f =>
              /^assets\//.test(f) ||
              ['manifest.webmanifest', 'icon.svg', 'icon-192.png', 'apple-touch-icon.png'].includes(f),
          )
          .map(f => './' + f),
      ];
      const version = crypto.createHash('sha256').update(JSON.stringify(all)).digest('hex').slice(0, 10);
      fs.writeFileSync(path.join(dir, 'sw.js'), worker(version, shell, lists));
    },
  };
}
